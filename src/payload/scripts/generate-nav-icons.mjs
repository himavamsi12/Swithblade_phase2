/**
 * Generates `src/app/(payload)/nav-icons.css`: a Lucide icon before each
 * admin sidebar link, keyed by Payload's `#nav-<slug>` ids. Pure CSS masks,
 * so no JavaScript runs and the icons take the link's text colour.
 *
 * Run `pnpm generate:nav-icons` after adding a collection to the sidebar.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Payload nav id (collection slug, or `global-<slug>`) → Lucide icon name. */
const ICONS = {
  orders: "shopping-cart",
  returns: "undo-2",
  carts: "shopping-basket",
  transactions: "credit-card",
  products: "tag",
  "product-categories": "folder-tree",
  "product-collections": "layers",
  variantTypes: "sliders-horizontal",
  media: "image",
  variants: "package",
  customers: "users",
  "customer-groups": "users-round",
  addresses: "map-pin",
  promotions: "badge-percent",
  campaigns: "megaphone",
  "price-lists": "circle-dollar-sign",
  users: "user-cog",
  regions: "globe",
  "tax-regions": "receipt",
  "return-reasons": "message-square-warning",
  "sales-channels": "store",
  "product-types": "shapes",
  "product-tags": "tags",
  "stock-locations": "warehouse",
  "shipping-options": "truck",
  "shipping-profiles": "boxes",
  "global-store": "settings",
};
const FALLBACK = "circle";

const toSvg = (node) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${node
    .map(
      ([tag, attrs]) =>
        `<${tag} ${Object.entries(attrs)
          .filter(([k]) => k !== "key")
          .map(([k, v]) => `${k}="${v === "currentColor" ? "black" : v}"`)
          .join(" ")}/>`,
    )
    .join("")}</svg>`;

const dataUri = async (name) => {
  const { __iconData } = await import(
    `lucide-react/dist/esm/icons/${name}.mjs`
  );
  return `url("data:image/svg+xml,${encodeURIComponent(toSvg(__iconData.node))}")`;
};

const rules = [];
for (const [id, name] of Object.entries(ICONS)) {
  rules.push(`#nav-${id} {\n  --sb-nav-icon: ${await dataUri(name)};\n}`);
}

const css = `/* Generated by src/payload/scripts/generate-nav-icons.mjs. Do not edit. */

.nav__link::before {
  content: "";
  flex-shrink: 0;
  width: 16px;
  height: 16px;
  margin-right: 10px;
  background-color: currentColor;
  -webkit-mask: var(--sb-nav-icon) center / contain no-repeat;
  mask: var(--sb-nav-icon) center / contain no-repeat;
}

.nav__link {
  --sb-nav-icon: ${await dataUri(FALLBACK)};
}

${rules.join("\n\n")}
`;

const out = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../app/(payload)/nav-icons.css",
);
await writeFile(out, css);
console.log(`Wrote ${Object.keys(ICONS).length} nav icons to ${out}`);
